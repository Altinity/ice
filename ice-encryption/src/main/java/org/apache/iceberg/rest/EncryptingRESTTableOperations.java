package org.apache.iceberg.rest;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Supplier;
import java.util.stream.Collectors;
import org.apache.iceberg.CatalogProperties;
import org.apache.iceberg.MetadataUpdate;
import org.apache.iceberg.TableMetadata;
import org.apache.iceberg.TableOperations;
import org.apache.iceberg.TableProperties;
import org.apache.iceberg.encryption.EncryptedKey;
import org.apache.iceberg.encryption.EncryptingFileIO;
import org.apache.iceberg.encryption.EncryptionManager;
import org.apache.iceberg.encryption.EncryptionUtil;
import org.apache.iceberg.encryption.KeyManagementClient;
import org.apache.iceberg.encryption.PlaintextEncryptionManager;
import org.apache.iceberg.encryption.StandardEncryptionManager;
import org.apache.iceberg.io.FileIO;
import org.apache.iceberg.relocated.com.google.common.base.Preconditions;

/**
 * {@link RESTTableOperations} with Iceberg table encryption, modeled after {@code
 * org.apache.iceberg.hive.HiveTableOperations}.
 *
 * <p>Data files are encrypted by writers via {@link #encryption()}; manifests and manifest lists
 * are encrypted by Iceberg core through {@link #io()}/{@link #encryption()}. Key encryption keys
 * and manifest list key metadata generated by the {@link StandardEncryptionManager} are sent to the
 * catalog as {@code add-encryption-key} updates on commit, so that the catalog server itself never
 * needs access to the KMS.
 */
class EncryptingRESTTableOperations extends RESTTableOperations {

  private final KeyManagementClient kmsClient;

  private String tableKeyId;
  private String dataKeyLength;
  private EncryptionManager encryptionManager;
  private EncryptingFileIO encryptingFileIO;

  // Keys generated by a previous encryption manager that are not in table metadata yet (e.g.
  // manifest list key metadata of a snapshot that is about to be committed by a transaction which
  // refreshes the table right before the commit).
  private final Map<String, EncryptedKey> uncommittedKeys = new LinkedHashMap<>();

  EncryptingRESTTableOperations(
      RESTClient client,
      String path,
      Supplier<Map<String, String>> readHeaders,
      Supplier<Map<String, String>> mutationHeaders,
      FileIO io,
      UpdateType updateType,
      List<MetadataUpdate> createChanges,
      TableMetadata current,
      Set<Endpoint> endpoints,
      KeyManagementClient kmsClient) {
    super(
        client,
        path,
        readHeaders,
        mutationHeaders,
        io,
        updateType,
        createChanges,
        current,
        endpoints);
    this.kmsClient = kmsClient;
  }

  @Override
  public synchronized EncryptionManager encryption() {
    if (encryptionManager != null) {
      return encryptionManager;
    }

    initEncryptionProps(current());
    if (tableKeyId == null) {
      return PlaintextEncryptionManager.instance();
    }

    Preconditions.checkArgument(
        kmsClient != null,
        "Table is encrypted (%s=%s) but no KMS is configured. Consider setting the '%s' or '%s' catalog property",
        TableProperties.ENCRYPTION_TABLE_KEY,
        tableKeyId,
        CatalogProperties.ENCRYPTION_KMS_TYPE,
        CatalogProperties.ENCRYPTION_KMS_IMPL);

    List<EncryptedKey> keys = new ArrayList<>();
    TableMetadata current = current();
    if (current != null && current.encryptionKeys() != null) {
      keys.addAll(current.encryptionKeys());
    }
    keys.addAll(uncommittedKeys.values());

    Map<String, String> props = new LinkedHashMap<>();
    props.put(TableProperties.ENCRYPTION_TABLE_KEY, tableKeyId);
    if (dataKeyLength != null) {
      props.put(TableProperties.ENCRYPTION_DEK_LENGTH, dataKeyLength);
    }
    encryptionManager = EncryptionUtil.createEncryptionManager(keys, props, kmsClient);
    return encryptionManager;
  }

  @Override
  public synchronized FileIO io() {
    EncryptionManager em = encryption();
    if (!(em instanceof StandardEncryptionManager)) {
      return super.io();
    }
    if (encryptingFileIO == null) {
      encryptingFileIO = EncryptingFileIO.combine(super.io(), em);
    }
    return encryptingFileIO;
  }

  @Override
  public TableMetadata refresh() {
    TableMetadata before = current();
    TableMetadata result = super.refresh();
    onMetadataChange(before);
    return result;
  }

  @Override
  public void commit(TableMetadata base, TableMetadata metadata) {
    TableMetadata before = current();
    initEncryptionProps(metadata);

    TableMetadata toCommit = metadata;
    EncryptionManager em = encryption();
    if (em instanceof StandardEncryptionManager) {
      TableMetadata.Builder builder = TableMetadata.buildFrom(metadata);
      for (EncryptedKey key : EncryptionUtil.encryptionKeys(em).values()) {
        builder.addEncryptionKey(key); // no-op for keys that are already present
      }
      toCommit = builder.build();
    }

    super.commit(base, toCommit);
    onMetadataChange(before);
  }

  @Override
  public TableOperations temp(TableMetadata uncommittedMetadata) {
    // e.g. create-table transactions, where current() is null until the commit
    initEncryptionProps(uncommittedMetadata);
    return super.temp(uncommittedMetadata);
  }

  private synchronized void initEncryptionProps(TableMetadata metadata) {
    if (tableKeyId != null || metadata == null) {
      return;
    }
    tableKeyId = metadata.properties().get(TableProperties.ENCRYPTION_TABLE_KEY);
    dataKeyLength = metadata.properties().get(TableProperties.ENCRYPTION_DEK_LENGTH);
  }

  private synchronized void onMetadataChange(TableMetadata before) {
    TableMetadata current = current();
    if (current == before) {
      return;
    }

    Set<String> committedKeyIds =
        current == null || current.encryptionKeys() == null
            ? Set.of()
            : current.encryptionKeys().stream()
                .map(EncryptedKey::keyId)
                .collect(Collectors.toSet());
    if (encryptionManager instanceof StandardEncryptionManager) {
      for (EncryptedKey key : EncryptionUtil.encryptionKeys(encryptionManager).values()) {
        uncommittedKeys.put(key.keyId(), key);
      }
    }
    uncommittedKeys.keySet().removeAll(committedKeyIds);

    // recreate with keys from the new metadata (e.g. added by other writers)
    encryptionManager = null;
    encryptingFileIO = null;
  }
}
